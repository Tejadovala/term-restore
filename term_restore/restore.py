"""Rebuild the tabs from a snapshot.

Nothing a tab was running is ever executed. Each restored tab opens in its old
working directory and prints the command that had been running; the command is
also pushed onto the shell's history so Up-arrow recalls it. Running it is the
user's keystroke, never ours.

Tabs are launched one invocation at a time -- the first with the backend's
new-window flag, the rest with its new-tab flag, which attach to the window just
created. gnome-terminal cannot do better: its `--` swallows the rest of the
argv, so a single command line only ever starts its first tab.
"""

from __future__ import annotations

import os
import shlex
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path

import shutil

from . import paths, probe, recording
from .model import Snapshot, Tab
from .terminals import GNOME_TERMINAL, Backend, by_name

TAB_TIMEOUT = 10.0
POLL = 0.1
MAX_TABS = 50

# Seeding the recalled command has to wait for the first prompt: running the
# `history` builtin while a startup file is still executing makes bash skip
# loading ~/.bash_history altogether, which would cost the user their history.
# PROMPT_COMMAND only accepts an array from bash 5.1 (Ubuntu 22.04); 20.04 ships
# 5.0, so the string form is kept as a fallback.
_SEED_TEMPLATE = """\
__tr_pc_array=0
((BASH_VERSINFO[0] > 5 || (BASH_VERSINFO[0] == 5 && BASH_VERSINFO[1] >= 1))) \\
    && __tr_pc_array=1
__tr_seed() {{
    history -s {command}
    if ((__tr_pc_array)); then
        PROMPT_COMMAND=( "${{PROMPT_COMMAND[@]:1}}" )
    else
        PROMPT_COMMAND=$__tr_pc_saved
    fi
    unset __tr_pc_array __tr_pc_saved
    unset -f __tr_seed
}}
if ((__tr_pc_array)); then
    PROMPT_COMMAND=( "__tr_seed" "${{PROMPT_COMMAND[@]}}" )
else
    __tr_pc_saved=$PROMPT_COMMAND
    PROMPT_COMMAND=__tr_seed
fi
"""


@dataclass
class Plan:
    """One tab's launch, resolved before anything is spawned."""

    index: int
    cwd: str
    command: str
    argv: list
    relocated: bool = False   # original cwd no longer exists
    bootstrap: str = ""       # "" when the shell is not bash
    log: str = ""             # session recording for the next restore
    replayed: int = 0         # scrollback lines shown from last session
    launch: list = field(default_factory=list)   # what the tab runs
    geometry: str = ""

    def shell_line(self) -> str:
        return " ".join(shlex.quote(a) for a in self.argv)


def _bootstrap(tab: Tab, dest: Path, prefill: bool, relocated: bool,
               announce: bool = True, replayed: int = 0) -> Path:
    cmd = tab.command_str
    lines = [
        "# generated by term-restore; overwritten on every restore",
        '[ -f "$HOME/.bashrc" ] && . "$HOME/.bashrc"',
    ]
    # Cyan tag, normal-weight text. The first version used \033[2m (faint) for
    # the whole line, which is close to invisible on several themes.
    tag = "\\033[36m[term-restore]\\033[0m"
    if relocated:
        lines.append(
            "printf '{} %s is gone; opened your home directory instead\\n' ".format(tag)
            + shlex.quote(tab.cwd)
        )
    if cmd:
        hint = "press Up to run it" if prefill else "not restored"
        lines.append(
            "printf '{} was running (%s): %s\\n' ".format(tag)
            + "{} {}".format(shlex.quote(hint), shlex.quote(cmd))
        )
        if prefill:
            lines.append(_SEED_TEMPLATE.format(command=shlex.quote(cmd)))
    elif announce and not relocated:
        # Without this a tab that was merely sitting at a prompt prints nothing,
        # which is indistinguishable from the restore having failed.
        lines.append("printf '{} restored this tab\\n'".format(tag))
    if replayed:
        lines.append(
            "printf '{} %s lines of scrollback above are from before the "
            "reboot\\n' {}".format(tag, replayed))
    dest.write_text("\n".join(lines) + "\n")
    return dest


def resolve_backend(snapshot: Snapshot, override: str = "") -> Backend:
    """Prefer an explicit choice, then the terminal the snapshot came from,
    then whatever is running now, then gnome-terminal."""
    if override:
        return by_name(override)
    if snapshot.terminal:
        try:
            return by_name(snapshot.terminal)
        except KeyError:
            pass
    backend, _ = probe.detect()
    return backend or GNOME_TERMINAL


def _launch_script(dest: Path, shell_command, log, replay) -> Path:
    """A one-line script per tab, so the command survives being passed as a
    single string by the batch launcher without three levels of quoting."""
    lines = ["# generated by term-restore; overwritten on every restore"]
    if log is not None:
        # The replay is printed before script is exec'd, so replayed text is not
        # written back into the new log; otherwise it would double every reboot.
        lines.append("cat {} 2>/dev/null".format(shlex.quote(str(replay))))
        inner = " ".join(shlex.quote(a) for a in shell_command)
        lines.append("exec script -q -f -a -c {} {}".format(
            shlex.quote(inner), shlex.quote(str(log))))
    else:
        lines.append("exec " + " ".join(shlex.quote(a) for a in shell_command))
    dest.write_text("\n".join(lines) + "\n")
    return dest


def build_plan(snapshot: Snapshot, prefill: bool = True, backend=None,
               max_tabs: int = MAX_TABS, announce: bool = True,
               record: bool = True):
    """(plans, warnings)."""
    backend = backend or resolve_backend(snapshot)
    boot_dir = paths.boot_dir()
    boot_dir.mkdir(parents=True, exist_ok=True)
    for stale in list(boot_dir.glob("tab-*.sh")) + list(boot_dir.glob("launch-*.sh")):
        stale.unlink()

    warnings = []
    tabs = snapshot.tabs
    if len(tabs) > max_tabs:
        warnings.append(
            "snapshot holds {} tabs; opening the first {} "
            "(raise with --max-tabs)".format(len(tabs), max_tabs)
        )
        tabs = tabs[:max_tabs]

    if record and shutil.which("script") is None:
        warnings.append("`script` not found; scrollback will not be recorded")
        record = False

    home = os.path.expanduser("~")
    plans = []
    logs = []
    for i, tab in enumerate(tabs):
        relocated = not os.path.isdir(tab.cwd)
        cwd = home if relocated else tab.cwd
        shell = tab.shell if os.path.exists(tab.shell) else "/bin/bash"

        log = replay = None
        replayed = 0
        if record:
            # Read-only here. The replay file is written in execute(), so that
            # planning -- including --dry-run -- changes nothing on disk.
            log = recording.allocate(tab.log)
            replay = log.with_suffix(".replay")
            replayed = recording.peek_replay(log)
            logs.append(str(log))

        if os.path.basename(shell) == "bash":
            boot = _bootstrap(tab, boot_dir / "tab-{}.sh".format(i), prefill,
                              relocated, announce, replayed)
            command = [shell, "--rcfile", str(boot)]
        else:
            # --rcfile is bash-only; another shell gets its directory back and
            # nothing else.
            boot, command = None, []

        launch = []
        if command:
            script = _launch_script(boot_dir / "launch-{}.sh".format(i),
                                    command, log if record else None, replay)
            launch = ["/bin/sh", str(script)]

        plans.append(
            Plan(
                index=i,
                cwd=cwd,
                command=tab.command_str,
                argv=backend.build_argv(cwd, first=(i == 0),
                                        geometry=snapshot.geometry or "",
                                        command=launch),
                relocated=relocated,
                bootstrap=str(boot) if boot else "",
                log=str(log) if log else "",
                replayed=replayed,
                launch=launch,
                geometry=snapshot.geometry or "",
            )
        )
    return plans, warnings


def _wait_for_new_tab(backend: Backend, before: set, servers):
    """Block until a new tab shell exists. Returns (appeared, server_pids).

    At boot the terminal process does not exist yet, so the first tab has to be
    waited for with a full /proc scan; once the server pids are known the poll
    reads only their children.
    """
    deadline = time.monotonic() + TAB_TIMEOUT
    while time.monotonic() < deadline:
        if servers:
            if probe.pty_children(servers) - before:
                return True, servers
        else:
            table = probe.ProcTable.scan()
            found = table.server_pids(backend)
            if found and set(table.tab_shells(backend)) - before:
                return True, found
        time.sleep(POLL)
    return False, servers


def _tabs_now(backend: Backend, servers):
    if servers:
        return probe.pty_children(servers)
    return set(probe.ProcTable.scan().tab_shells(backend))


def _wait_for_tabs(backend: Backend, before: set, servers, want: int):
    """Block until `want` new tab shells exist. Returns (count, servers)."""
    deadline = time.monotonic() + TAB_TIMEOUT
    while time.monotonic() < deadline:
        if not servers:
            table = probe.ProcTable.scan()
            servers = table.server_pids(backend)
        new = _tabs_now(backend, servers) - before if servers else set()
        if len(new) >= want:
            return len(new), servers
        time.sleep(POLL)
    return len(_tabs_now(backend, servers) - before) if servers else 0, servers


def _run(argv):
    """(ok, message)."""
    try:
        subprocess.run(argv, check=True, capture_output=True, text=True,
                       timeout=60)
    except FileNotFoundError:
        return False, "{} is not installed".format(argv[0])
    except subprocess.CalledProcessError as exc:
        return False, (exc.stderr or "").strip() or str(exc)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, str(exc)
    return True, ""


def _execute_batch(plans, backend: Backend):
    """Open every tab in one window with a single invocation.

    Issuing one call per tab does not work at login: a bare new-tab flag
    attaches to whatever window has focus, and the window just created is not
    focused yet, so every tab lands in a window of its own.
    """
    argv = backend.build_batch_argv([(p.cwd, p.launch) for p in plans],
                                    plans[0].geometry)
    servers = probe.ProcTable.scan().server_pids(backend)
    before = _tabs_now(backend, servers)
    ok, message = _run(argv)
    if not ok:
        return 0, [message]
    appeared, _ = _wait_for_tabs(backend, before, servers, len(plans))
    if appeared < len(plans):
        return appeared, ["only {} of {} tabs appeared".format(
            appeared, len(plans))]
    return appeared, []


def _execute_serially(plans, backend: Backend):
    opened, warnings = 0, []
    servers = probe.ProcTable.scan().server_pids(backend)
    for plan in plans:
        before = _tabs_now(backend, servers)
        ok, message = _run(plan.argv)
        if not ok:
            warnings.append("tab {}: {}".format(plan.index + 1, message))
            if "not installed" in message:
                break
            continue
        opened += 1
        _, servers = _wait_for_tabs(backend, before, servers, 1)
    return opened, warnings


def execute(plans, backend=None):
    """Launch every planned tab. Returns (tabs_opened, warnings, mode).

    `mode` records which path ran -- it is the only evidence at login of
    whether the tabs were grouped into one window or opened one at a time.
    """
    backend = backend or GNOME_TERMINAL
    if not plans:
        return 0, [], "nothing"
    for plan in plans:
        if plan.log:
            recording.prepare_replay(Path(plan.log))

    warnings = []
    if backend.can_batch and all(p.launch for p in plans):
        opened, batch_warnings = _execute_batch(plans, backend)
        if opened == len(plans):
            _prune_logs(plans)
            return opened, batch_warnings, "one window"
        warnings += batch_warnings
        if opened:
            # Tabs are already open; opening them again would double them.
            _prune_logs(plans)
            return (opened, warnings + ["some tabs may be in their own window"],
                    "partial")
        warnings.append("single-window launch failed; falling back to one "
                        "invocation per tab")

    opened, serial_warnings = _execute_serially(plans, backend)
    _prune_logs(plans)
    return opened, warnings + serial_warnings, "one tab at a time"


def _prune_logs(plans) -> None:
    """Drop stale recordings, keeping this restore's logs and those of any tab
    that is still recording -- pruning to the plan alone would delete the logs
    of live tabs that were not part of it."""
    keep = {p.log for p in plans if p.log}
    if not keep:
        return
    keep |= {t.log for t in probe.take_snapshot().tabs if t.log}
    recording.prune(keep)
